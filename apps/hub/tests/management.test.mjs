import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { randomUUID, scryptSync } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import express from "express";
import { createHubDatabase } from "../dist/db.js";
import { createManagementRouter } from "../dist/management.js";
import { emptyVenueProfile } from "@exa-foh/shared";

test("venue management preserves service data and enforces authenticated lifecycle operations", async t => {
  const directory = mkdtempSync(join(tmpdir(), "exa-management-"));
  const dbPath = join(directory, "hub.sqlite");
  const hub = createHubDatabase(dbPath);
  const before = hub.loadSnapshot();
  const app = express(); app.use(express.json());
  app.use("/api/manage", createManagementRouter(dbPath, "org-test", () => hub.loadSnapshot()));
  const server = app.listen(0, "127.0.0.1");
  await new Promise(resolve => server.once("listening", resolve));
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); rmSync(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}/api/manage`;
  let token;
  async function request(path, method = "GET", body, auth = token, key) {
    const response = await fetch(`${base}${path}`, { method, headers: { "Content-Type": "application/json", ...(auth ? { Authorization: `Bearer ${auth}` } : {}), ...(key ? { "Idempotency-Key": key } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json() };
  }
  assert.equal((await request("/venues")).status, 401);
  assert.equal((await request("/venues", "GET", undefined, "a".repeat(64))).status, 401);
  const owner = { name: "Test Owner", email: "owner@example.test", password: "test-password-1234", setupKey: readFileSync(`${dbPath}.setup-key`, "utf8") };
  assert.equal((await request("/auth/setup", "POST", { ...owner, setupKey: "invalid" })).status, 403);
  const setup = await request("/auth/setup", "POST", owner);
  assert.equal(setup.status, 201); token = setup.body.token;
  assert.equal((await request("/auth/setup", "POST", owner)).status, 409);
  assert.equal((await request("/auth/login", "POST", { email: owner.email, password: "wrong" })).status, 401);
  const seeded = await request("/venues");
  assert.equal(seeded.body.total, 1);
  const importedId = seeded.body.items[0].id;
  assert.equal((await request(`/venues/${importedId}`)).body.linkedService.id, before.event.id);
  assert.equal((await request(`/venues/${importedId}/status`, "POST", { version: 1, status: "archived", reason: "Test block" })).status, 409);
  const profile = { ...emptyVenueProfile(), name: "Test Rooftop", city: "Lagos", address: "12 Marina Road" };
  assert.equal((await request("/venues", "POST", { ...profile, timezone: "bad/timezone" })).status, 422);
  assert.equal((await request("/venues", "POST", { ...profile, hours: Array(7).fill(profile.hours[0]) })).status, 422);
  const requestKey = randomUUID();
  const created = await request("/venues", "POST", profile, token, requestKey);
  assert.equal(created.status, 201);
  const id = created.body.id;
  assert.equal((await request("/venues", "POST", profile, token, requestKey)).body.id, id);
  assert.equal((await request("/venues", "POST", { ...profile, name: "Different name" }, token, requestKey)).status, 409);
  assert.equal(created.body.status, "draft");
  const edit = await request(`/venues/${id}`, "PATCH", { ...profile, city: "Abuja", version: 1 });
  assert.equal(edit.status, 200);
  assert.equal(edit.body.version, 2);
  assert.equal((await request(`/venues/${id}`, "PATCH", { ...profile, version: 1 })).status, 409);
  assert.equal((await request("/venues?q=Abuja")).body.total, 1);
  assert.equal((await request("/venues?q=does-not-exist")).body.total, 0);
  const active = await request(`/venues/${id}/status`, "POST", { version: 2, status: "active", reason: "Ready for operation" });
  assert.equal(active.status, 200);
  assert.equal((await request(`/venues/${id}`, "PATCH", { ...profile, address: "", version: 3 })).status, 422);
  assert.equal((await request(`/venues/${id}/status`, "POST", { version: 3, status: "draft", reason: "Invalid transition" })).status, 409);
  const archived = await request(`/venues/${id}/status`, "POST", { version: 3, status: "archived", reason: "Retired location" });
  assert.equal(archived.status, 200);
  assert.equal((await request(`/venues/${id}`, "PATCH", { ...profile, version: 4 })).status, 409);
  const restored = await request(`/venues/${id}/status`, "POST", { version: 4, status: "draft", reason: "Reopen profile" });
  assert.equal(restored.status, 200);
  const detail = await request(`/venues/${id}`);
  assert.equal(detail.body.activity.length, 5);
  assert.equal(detail.body.venue.city, "Abuja");

  // Exercise limited grants with a provisioned account, independent of client role controls.
  const sql = new DatabaseSync(dbPath);
  const viewer = { id: randomUUID(), name: "Viewer", email: "viewer@example.test", role: "viewer", venueIds: [id], organizationId: "org-test", salt: "test-salt", passwordHash: scryptSync("viewer-password", "test-salt", 64).toString("hex"), active: true };
  sql.prepare("INSERT INTO management_accounts VALUES (?, ?, ?)").run(viewer.id, viewer.email, JSON.stringify(viewer));
  const viewerLogin = await request("/auth/login", "POST", { email: viewer.email, password: "viewer-password" });
  const viewerToken = viewerLogin.body.token;
  assert.equal((await request("/venues", "GET", undefined, viewerToken)).body.total, 1);
  assert.equal((await request(`/venues/${id}`, "GET", undefined, viewerToken)).body.canEdit, false);
  assert.equal((await request(`/venues/${importedId}`, "GET", undefined, viewerToken)).status, 403);
  assert.equal((await request("/venues", "POST", profile, viewerToken)).status, 403);
  assert.equal((await request(`/venues/${id}`, "PATCH", { ...profile, version: 5 }, viewerToken)).status, 403);
  viewer.active = false;
  sql.prepare("UPDATE management_accounts SET data = ? WHERE id = ?").run(JSON.stringify(viewer), viewer.id);
  assert.equal((await request("/venues", "GET", undefined, viewerToken)).status, 403);
  sql.close();

  hub.saveSnapshot(before);
  assert.deepEqual(hub.loadSnapshot().orders, before.orders);
  assert.deepEqual(hub.loadSnapshot().inventory, before.inventory);
  assert.equal((await request(`/venues/${id}`)).body.venue.version, 5);
  createManagementRouter(dbPath, "org-test", () => hub.loadSnapshot());
  assert.equal((await request("/venues")).body.total, 2, "restarting migration must not duplicate venues");
  await request("/auth/logout", "POST", {});
  assert.equal((await request("/venues")).status, 401);
});
