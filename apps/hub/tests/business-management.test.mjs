import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { randomUUID, scryptSync } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import express from "express";
import { createHubDatabase } from "../dist/db.js";
import { createManagementRouter } from "../dist/management.js";
import { emptyVenueProfile } from "@exa-foh/shared";

test("events, storefronts, floor and QR stay scoped and cloning excludes operational state", async t => {
  const directory = mkdtempSync(join(tmpdir(), "exa-business-"));
  const dbPath = join(directory, "hub.sqlite");
  const hub = createHubDatabase(dbPath); const before = hub.loadSnapshot();
  const app = express(); app.use(express.json());
  const management = createManagementRouter(dbPath, "org-test", () => hub.loadSnapshot());
  app.use("/api/manage", management);
  const server = app.listen(0, "127.0.0.1");
  await new Promise(resolve => server.once("listening", resolve));
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); rmSync(directory, { recursive: true, force: true }); });
  const root = `http://127.0.0.1:${server.address().port}/api/manage`; let token;
  async function request(path, method = "GET", body, auth = token, key) {
    const response = await fetch(`${root}${path}`, { method, headers: { "Content-Type": "application/json", ...(auth ? { Authorization: `Bearer ${auth}` } : {}), ...(key ? { "Idempotency-Key": key } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json() };
  }
  async function create(kind, data) {
    const result = await request(`/${kind}`, "POST", data);
    assert.equal(result.status, 201, JSON.stringify(result.body)); return result.body;
  }
  async function status(kind, record, value, expected = 200) {
    const result = await request(`/${kind}/${record.id}/status`, "POST", { version: record.version, status: value, reason: "Test transition" });
    assert.equal(result.status, expected, JSON.stringify(result.body)); return result.body;
  }
  assert.equal((await request("/events")).status, 401);
  const owner = await request("/auth/setup", "POST", { name: "Business Owner", email: "owner@example.test", password: "test-password-1234", setupKey: readFileSync(`${dbPath}.setup-key`, "utf8") });
  token = owner.body.token;
  const venues = [];
  for (const name of ["Venue A", "Venue B"]) venues.push(await create("venues", { ...emptyVenueProfile(), name, address: "Main Street", city: "Lagos" }));
  const eventInput = { name: "Event A", venueId: venues[0].id, location: "", timezone: "Africa/Lagos", startsAt: "2026-10-01T18:00:00Z", endsAt: "2026-10-02T02:00:00Z", organizer: "Event Manager", notes: "" };
  assert.equal((await request("/events", "POST", { ...eventInput, endsAt: "2026-09-01T00:00:00Z" })).status, 422);
  let event = await create("events", eventInput);
  const otherEvent = await create("events", { ...eventInput, name: "Event B", venueId: venues[1].id });
  await status("events", event, "ready", 422);
  await status("events", event, "live", 409);
  const vendors = [];
  for (const name of ["Vendor A", "Vendor B"]) vendors.push(await create("vendors", { name, kind: "external", contactName: "Manager", email: "", phone: "", notes: "" }));
  const ref = { scopeType: "event", scopeId: event.id };
  const storeInput = { name: "Main Bar", ...ref, vendorId: vendors[0].id, kind: "bar", prepStation: "Bar counter", manualConfirmation: true, fulfillment: "table", sectionIds: [], commercialTerms: "10 percent agreed", notes: "" };
  let store = await create("storefronts", storeInput);
  const secondStore = await create("storefronts", { ...storeInput, name: "Kitchen", vendorId: vendors[1].id });
  assert.equal((await request("/storefronts", "POST", storeInput)).status, 409);
  assert.equal((await request(`/storefronts?vendorId=${vendors[0].id}`)).body.total, 1);
  await status("vendors", vendors[0], "archived", 409);
  store = await status("storefronts", store, "active");
  const section = await create("floor", { name: "VIP", ...ref, kind: "section", parentId: null, storefrontId: null, capacity: 40 });
  const table = await create("floor", { name: "Table 1", ...ref, kind: "table", parentId: section.id, storefrontId: store.id, capacity: 1 });
  const seat = await create("floor", { name: "Seat 1", ...ref, kind: "seat", parentId: table.id, storefrontId: store.id, capacity: 1 });
  assert.equal((await request("/floor", "POST", { name: "Seat 2", ...ref, kind: "seat", parentId: table.id, storefrontId: store.id, capacity: 1 })).status, 409);
  assert.equal((await request("/floor", "POST", { name: "Wrong scope", scopeType: "event", scopeId: otherEvent.id, kind: "table", parentId: section.id, storefrontId: store.id, capacity: 4 })).status, 422);
  await status("floor", table, "archived", 409);
  await status("storefronts", store, "archived", 409);
  const entry = await request(`/entry/${store.qrToken}`, "GET", undefined, null);
  assert.equal(entry.status, 200); assert.equal(entry.body.open, false); assert.equal(entry.body.storeId, undefined);
  const rotated = await request(`/storefronts/${store.id}/qr`, "POST", { version: store.version, action: "rotate" });
  assert.equal(rotated.status, 200);
  assert.equal((await request(`/entry/${store.qrToken}`, "GET", undefined, null)).status, 410);
  store = rotated.body;
  assert.equal((await request(`/entry/${store.qrToken}`, "GET", undefined, null)).status, 200);
  const disabled = await request(`/storefronts/${store.id}/qr`, "POST", { version: store.version, action: "disable" });
  assert.equal(disabled.status, 200);
  assert.equal((await request(`/entry/${store.qrToken}`, "GET", undefined, null)).status, 410);
  store = disabled.body;
  event = (await request(`/events/${event.id}`)).body.record;
  event = await status("events", event, "ready");
  const changed = await request(`/storefronts/${store.id}`, "PATCH", { ...storeInput, prepStation: "VIP prep", version: store.version });
  assert.equal(changed.status, 200);
  assert.equal((await request(`/events/${event.id}`)).body.record.status, "draft", "configuration changes invalidate readiness");
  assert.equal((await request(`/storefronts/${store.id}`, "PATCH", { ...storeInput, version: store.version })).status, 409);
  const cloneKey = randomUUID();
  const cloneInput = { name: "Event A next week", startsAt: "2026-10-08T18:00:00Z", endsAt: "2026-10-09T02:00:00Z" };
  const clone = await request(`/events/${event.id}/clone`, "POST", cloneInput, token, cloneKey);
  assert.equal(clone.status, 201, JSON.stringify(clone.body));
  assert.equal((await request(`/events/${event.id}/clone`, "POST", cloneInput, token, cloneKey)).body.id, clone.body.id);
  assert.equal(clone.body.status, "draft"); assert.equal(clone.body.legacyUnitId, undefined);
  const clonedStores = (await request(`/storefronts?scopeType=event&scopeId=${clone.body.id}`)).body.items;
  assert.equal(clonedStores.length, 2);
  for (const cloned of clonedStores) { assert.equal(cloned.status, "draft"); assert.equal(cloned.commercialTerms, ""); assert.ok(![store.id, secondStore.id].includes(cloned.id)); assert.equal(cloned.legacyStoreId, undefined); }
  const clonedPlaces = (await request(`/floor?scopeType=event&scopeId=${clone.body.id}`)).body.items;
  assert.equal(clonedPlaces.length, 3);
  const clonedTable = clonedPlaces.find(p => p.kind === "table");
  const clonedSeat = clonedPlaces.find(p => p.kind === "seat");
  assert.equal(clonedSeat.parentId, clonedTable.id);
  assert.notEqual(clonedSeat.qrToken, seat.qrToken);

  const sql = new DatabaseSync(dbPath);
  const manager = { id: randomUUID(), name: "Scoped Manager", email: "manager@example.test", role: "manager", venueIds: [venues[0].id], organizationId: "org-test", salt: "test-salt", passwordHash: scryptSync("manager-password", "test-salt", 64).toString("hex"), active: true };
  sql.prepare("INSERT INTO management_accounts VALUES (?, ?, ?)").run(manager.id, manager.email, JSON.stringify(manager)); sql.close();
  const login = await request("/auth/login", "POST", { email: manager.email, password: "manager-password" });
  const managerToken = login.body.token;
  assert.equal((await request(`/events/${otherEvent.id}`, "GET", undefined, managerToken)).status, 403);
  assert.equal((await request("/storefronts", "POST", { ...storeInput, scopeId: otherEvent.id }, managerToken)).status, 403);
  assert.equal((await request("/vendors", "POST", { name: "Unauthorized vendor", kind: "external", contactName: "", email: "", phone: "", notes: "" }, managerToken)).status, 403);
  const options = (await request("/business/options", "GET", undefined, managerToken)).body;
  assert.ok(!options.events.some(e => e.id === otherEvent.id));
  assert.equal(options.vendors.length, 2);
  assert.equal((await request(`/venues/${venues[0].id}/status`, "POST", { status: "archived", version: venues[0].version, reason: "Unsafe archive" })).status, 409);
  const legacy = (await request(`/storefronts/${before.stores[0].id}`)).body.record;
  const legacyEntry = management.resolveEntry(legacy.qrToken);
  assert.equal(legacyEntry.open, true); assert.equal(legacyEntry.storeId, before.stores[0].id);
  const current = hub.loadSnapshot(); current.event.status = "closed"; hub.saveSnapshot(current);
  assert.equal(management.resolveEntry(legacy.qrToken).open, false);
  hub.saveSnapshot(before);
  assert.deepEqual(hub.loadSnapshot().orders, before.orders);
  assert.deepEqual(hub.loadSnapshot().inventory, before.inventory);
  const count = (await request("/events")).body.total;
  createManagementRouter(dbPath, "org-test", () => hub.loadSnapshot());
  assert.equal((await request("/events")).body.total, count);
});
