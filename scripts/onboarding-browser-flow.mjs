import { config } from "dotenv";
import { PrismaClient } from "@prisma/client";
import { chromium, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { mkdir } from "node:fs/promises";
import assert from "node:assert/strict";
config({ path: "apps/cloud/.env", quiet: true });
const db = new PrismaClient(), slug = `wizard-${randomUUID().slice(0, 8)}`;
const origin = process.env.BROWSER_APP_ORIGIN ?? "http://app.localhost:5173";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } }), page = await context.newPage();
page.setDefaultTimeout(30_000);
const errors = []; page.on("pageerror", error => errors.push(error.message));
try {
  await mkdir("test-results/onboarding", { recursive: true });
  await page.goto(`${origin}/signup`);
  await page.getByLabel("Organization name", { exact: true }).fill("Onboarding test business");
  await page.locator('input[name="slug"]').fill(slug);
  await page.getByLabel("Full name", { exact: true }).fill("Test Owner");
  await page.getByLabel("Email", { exact: true }).fill("owner@example.test");
  await page.getByLabel("Password", { exact: true }).fill("onboarding-browser-password");
  await page.getByRole("button", { name: "Create workspace", exact: true }).click();
  await page.getByRole("link", { name: "Open workspace", exact: true }).click();
  await page.getByLabel("Email", { exact: true }).fill("owner@example.test");
  await page.getByLabel("Password", { exact: true }).fill("onboarding-browser-password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.waitForURL("**/dashboard"); await page.getByRole("button", { name: "Continue onboarding", exact: true }).click(); await expect(page.getByRole("dialog", { name: "Business onboarding", exact: true })).toBeVisible();
  await expect(page.getByText("What would you like to manage first?", { exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/onboarding/choice-desktop.png", fullPage: true });
  await page.getByRole("button", { name: /A physical location/ }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("What is this branch or location called?", { exact: true }).fill("Lekki branch");
  await page.getByLabel("Where is it? (optional)", { exact: true }).fill("Lagos");
  await page.getByRole("button", { name: "Save & finish later", exact: true }).click();
  await page.waitForURL("**/dashboard");
  await expect(page.getByRole("dialog", { name: "Business onboarding", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Continue onboarding", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: "Continue onboarding", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Continue onboarding", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Business onboarding", exact: true })).toHaveJSProperty("open", true);
  const bounds = await page.getByRole("dialog", { name: "Business onboarding", exact: true }).boundingBox();
  assert.equal(bounds.width, 1440); assert.equal(bounds.height, 1000);
  await expect(page.getByLabel("What is this branch or location called?", { exact: true })).toHaveValue("Lekki branch");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Tables", { exact: true }).fill("3");
  await page.getByRole("button", { name: "Add section", exact: true }).click();
  await page.getByLabel("Section name", { exact: true }).nth(1).fill("Terrace");
  await page.getByLabel("Tables", { exact: true }).nth(1).fill("2");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator("aside").evaluate(node => node.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.screenshot({ path: "test-results/onboarding/layout-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "mobile has no horizontal overflow");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByText("Main dining · 3 tables", { exact: true })).toBeVisible();
  await expect(page.getByText("Terrace · 2 tables", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Create my setup", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your starting setup is ready", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Save and close onboarding", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Business onboarding", exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("button", { name: "Continue onboarding", exact: true })).toHaveCount(0);
  const tenant = await db.tenant.findUnique({ where: { slug } });
  assert.equal(await db.venue.count({ where: { tenantId: tenant.id } }), 1);
  assert.equal(await db.storefront.count({ where: { tenantId: tenant.id } }), 1);
  assert.equal(await db.workspaceRecord.count({ where: { tenantId: tenant.id, kind: "floor" } }), 7);
  assert.deepEqual(errors, []);
  console.log("Onboarding: new-owner routing, saved exit, reload/resume, mobile layout, creation and retry-safe completion passed.");
} finally { await context.close(); await browser.close(); await db.tenant.deleteMany({ where: { slug } }); await db.$disconnect(); }
