import assert from "node:assert/strict";
import { join, resolve } from "node:path";
import sharp from "sharp";

export async function verifyBrandingFlow(page, artifacts) {
  const origin = new URL(page.url()).origin;
  const operations = await (await page.request.get(`${origin}/api/manage/operations`)).json();
  const event = operations.items.find(item => item.scopeType === "event" && item.status === "live");
  const header = await sharp({ create: { width: 1600, height: 500, channels: 4, background: "#087e8b" } }).composite([{ input: Buffer.from('<svg width="1600" height="500"><text x="80" y="275" fill="white" font-size="100" font-family="sans-serif">HARBOUR NIGHTS</text></svg>') }]).png().toBuffer();
  const background = await sharp({ create: { width: 160, height: 160, channels: 4, background: "#12424a" } }).png().toBuffer();
  const logo = await sharp({ create: { width: 300, height: 120, channels: 4, background: "#ffffff" } }).composite([{ input: Buffer.from('<svg width="300" height="120"><text x="20" y="80" fill="#d62d62" font-size="50" font-family="sans-serif">PARTNER</text></svg>') }]).png().toBuffer();
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.goto(`${origin}/events/${event.id}?tab=appearance`);
  await page.getByRole("heading", { name: "Colours", exact: true }).waitFor();
  await page.getByLabel("Background colour").fill("#12424a");
  await page.getByLabel("Menu surface colour").fill("#ffffff");
  await page.getByLabel("Accent colour").fill("#d62d62");
  async function upload(label, name, buffer) {
    await page.getByLabel(label, { exact: true }).setInputFiles({ name, mimeType: "image/png", buffer });
    await page.getByRole("button", { name: "Save appearance", exact: true }).waitFor();
    await page.waitForFunction(() => !document.querySelector("fieldset").disabled);
  }
  await upload("Header image", "header.png", header);
  await upload("Background image", "background.png", background);
  await page.getByLabel("Background layout").selectOption("tile");
  await page.getByLabel("Custom font", { exact: true }).setInputFiles(resolve("node_modules/next/dist/next-devtools/server/font/geist-latin.woff2"));
  await page.getByText("geist-latin.woff2", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Add sponsor", exact: true }).click();
  await page.getByLabel("Sponsor name", { exact: true }).fill("Partner One");
  await upload("Sponsor logo", "partner.png", logo);
  await page.getByLabel("Sponsor website", { exact: true }).fill("https://example.com");
  await page.getByRole("button", { name: "Save appearance", exact: true }).click();
  await page.getByText("Guest appearance saved", { exact: true }).waitFor();
  await page.reload();
  await page.getByLabel("Background colour").waitFor();
  assert.equal(await page.getByLabel("Background colour").inputValue(), "#12424a");
  await page.screenshot({ path: join(artifacts, "event-appearance-desktop.png"), fullPage: true });
  const saved = await (await page.request.get(`${origin}/api/manage/events/${event.id}/branding`)).json();
  const stores = await (await page.request.get(`${origin}/api/manage/storefronts?scopeType=event&scopeId=${event.id}`)).json();
  const inventory = await (await page.request.get(`${origin}/api/manage/service/${event.id}/api/snapshot`)).json();
  const store = stores.items.find(s => s.id === inventory.menuItems[0].storeId && s.qrToken);
  await page.goto(`${origin}/service/inventory?operation=${event.id}`);
  const photoInput = page.locator('input[type="file"]').first();
  await photoInput.waitFor();
  const photoName = (await photoInput.getAttribute("aria-label")).replace("Photo for ", "");
  await photoInput.setInputFiles({ name: "product.png", mimeType: "image/png", buffer: logo });
  await page.getByText("Product photo updated", { exact: true }).waitFor();
  await page.getByRole("img", { name: photoName, exact: true }).waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll("img")].every(img => img.complete && img.naturalWidth > 0));
  const guest = await page.context().newPage();
  const errors = []; guest.on("pageerror", error => errors.push(error.message));
  await guest.goto(`http://localhost:5189/entry/${store.qrToken}`);
  await guest.getByRole("heading", { name: "Available now", exact: true }).waitFor();
  await guest.getByRole("img", { name: photoName, exact: true }).waitFor();
  await guest.getByRole("img", { name: "Partner One", exact: true }).waitFor();
  await guest.waitForFunction(() => [...document.querySelectorAll("img")].every(img => img.complete && img.naturalWidth > 0));
  assert.equal(await guest.locator('[data-guest-branding]').evaluate(element => getComputedStyle(element).backgroundColor), "rgb(18, 66, 74)");
  const family = `EXAGuest-${saved.branding.fontAssetId}`;
  assert.equal(await guest.evaluate(async family => (await document.fonts.load(`16px "${family}"`)).length > 0, family), true, "uploaded font renders");
  assert.equal(await guest.getByRole("link", { name: "Partner One" }).getAttribute("href"), "https://example.com");
  await guest.getByRole("button", { name: "Add one" }).first().click();
  assert.equal(await guest.getByRole("button", { name: "Send order", exact: true }).isEnabled(), true, "branding preserves ordering controls");
  await guest.screenshot({ path: join(artifacts, "branded-guest-desktop.png"), fullPage: true });
  await guest.setViewportSize({ width: 390, height: 844 });
  await guest.reload();
  await guest.getByRole("heading", { name: "Available now", exact: true }).waitFor();
  await guest.waitForFunction(() => [...document.querySelectorAll("img")].every(img => img.complete && img.naturalWidth > 0));
  await guest.evaluate(() => document.fonts.ready);
  assert.equal(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await guest.screenshot({ path: join(artifacts, "branded-guest-mobile.png"), fullPage: true });
  assert.deepEqual(errors, []);
  await guest.close();
  await page.goto(`${origin}/events/${event.id}?tab=appearance`);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Mobile preview" }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: join(artifacts, "event-appearance-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  console.log("PASS: event branding uploads, save/reload, custom font loading, live QR menu, sponsor links and responsive layouts");
}
